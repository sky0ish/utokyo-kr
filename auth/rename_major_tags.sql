-- ═══════════════════════════════════════════════════════════
--  전공별모임 글의 옛 말머리를 지금 이름으로 바꿉니다.
--
--   말머리 이름을 여러 번 다듬었더니, 예전 이름으로 달린 글이 남아
--   말머리 줄에 「인문사회」 처럼 옛 이름이 함께 보입니다.
--   이 SQL 을 한 번 돌리면 모두 지금 이름으로 모입니다.
--
--   실행 : Supabase 대시보드 → SQL Editor → 붙여넣기 → Run
--   ※ 여러 번 실행해도 안전합니다.
-- ═══════════════════════════════════════════════════════════

-- ── ① 지금 어떤 말머리가 쓰이고 있는지 ──
select split_part(split_part(title, ']', 1), '[', 2) as "말머리",
       count(*) as "글수"
  from public.posts
 where category = 'major'
 group by 1
 order by count(*) desc;


-- ── ② 옛 이름을 지금 이름으로 ──
update public.posts p
   set title = regexp_replace(
         title,
         '^\s*[\[【]\s*' || old || '\s*[\]】]\s*',
         '[' || new || '] '
       )
  from (values
    ('인문사회',          '인문·사회·교육'),
    ('인문·사회',          '인문·사회·교육'),
    ('교육',              '인문·사회·교육'),
    ('총합문화',          '교양·총합문화'),
    ('법학부',            '법학·정치·공공정책'),
    ('법학·공공정책',      '법학·정치·공공정책'),
    ('법학·정치',          '법학·정치·공공정책'),
    ('경제학부',          '경제·경영학'),
    ('의약',              '의학·약학·간호학'),
    ('약학',              '의학·약학·간호학'),
    ('의학',              '의학·약학·간호학'),
    ('재료·화학',          '화학·응용화학·재료'),
    ('응용화학계열',       '화학·응용화학·재료'),
    ('도시·토목·환경',     '도시환경토목(C.U.E)'),
    ('C.U.E',            '도시환경토목(C.U.E)'),
    ('CUE',              '도시환경토목(C.U.E)'),
    ('전기전자기계',       '전기·기계'),
    ('전기·기계·항공',      '전기·기계'),
    ('생산기술연구소',      '생산·선단과학·기술기타'),
    ('생산·첨단·기술기타',   '생산·선단과학·기술기타'),
    ('건축학부',          '건축학'),
    ('농학생명',          '농학부'),
    ('공학 기타',          '기타')
  ) as t(old, new)
 where p.category = 'major'
   and p.title ~ ('^\s*[\[【]\s*' || t.old || '\s*[\]】]');


-- ── ③ 바꾼 뒤 모습 ──
select split_part(split_part(title, ']', 1), '[', 2) as "말머리",
       count(*) as "글수"
  from public.posts
 where category = 'major'
 group by 1
 order by count(*) desc;
