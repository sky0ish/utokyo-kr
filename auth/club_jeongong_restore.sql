--  소모임 「전공별」 되살리기 ② — 실제로 고칩니다
--
--  ⚠️ 먼저 auth/club_jeongong_check.sql 을 돌려 **눈으로 확인**하십시오.
--     여기 적힌 다섯 건이 정말 포럼에 가 있는지 보고 나서 이것을 돌리세요.
--  ⚠️ auth/posts_audit.sql 을 먼저 돌려 두시면, 이 되살리기도 기록에 남아
--     마음에 안 들면 posts_restore(기록번호) 로 다시 되돌릴 수 있습니다.
--
--  한 덩이(transaction)라 중간에 어긋나면 아무것도 바뀌지 않습니다.
--  ㉮ 만 돌릴지, ㉯ 까지 돌릴지는 아래에서 고르십시오.
-- ═══════════════════════════════════════════════════════════

begin;

-- ───────────────────────────────────────────────────────────
--  ㉮ 포럼으로 옮겨졌던 「응용화학계열 동문회」 글 5건을 소모임으로
--
--  이 다섯은 옛 import SQL(band_import.sql)에 category='club' 으로
--  또렷이 적혀 있던 글입니다. 되짚는 근거가 확실합니다.
-- ───────────────────────────────────────────────────────────
update public.posts
   set category = 'club',
       title    = '[전공별] ' || regexp_replace(title, '^\s*\[[^\]]*\]\s*', '')
 where org = 'OB'
   and category <> 'club'
   and regexp_replace(title, '^\s*\[[^\]]*\]\s*', '') like any (array[
         '동경대 응용화학계열 전반기 모임%',
         '응용화학계열 동문회 정기 세미나를%',
         '오늘 응용화학계열 송년회가 있었습니다%',
         '2023년 2월24일(금) 부산대학교에서 응용화학계열%',
         '오늘 7/22 응용화학부 동문회 모임이 있었습니다%'
       ]);


-- ───────────────────────────────────────────────────────────
--  ㉯ 소모임에 있으면서 전공 모임인데 다른 말머리를 단 글에
--     [전공별] 을 붙입니다.
--
--  ※ 이것은 낱말로 가려내는 것이라 **딱 떨어지지 않습니다.**
--     ①의 4번 질의로 목록을 먼저 보시고, 마음에 들 때만 돌리십시오.
--     싫으시면 아래 여섯 줄을 통째로 주석 처리(맨 앞에 --)하고 돌리세요.
--
--  club_tags.sql 3) 과 같은 잣대이되, 골프·등산·친목은 건드리지 않습니다.
-- ───────────────────────────────────────────────────────────
update public.posts
   set title = '[전공별] ' || regexp_replace(title, '^\s*\[[^\]]*\]\s*', '')
 where org = 'OB' and category = 'club'
   and title !~ '^\[(골프|등산|친목|전공별)\]'
   and (title ~ '(공학부|농학부|약학부|의학부|법학부|경제학부|문학부|이학부|건축|화학|전기|기계|도시|수의|응용화학|계열|학과|전공|연구실|단과대)'
     or content ~ '(공학부|농학부|약학부|의학부|법학부|경제학부|문학부|이학부|응용화학계열|단과대|학과 모임|전공 모임)');


commit;


-- ═══════════════════════════════════════════════════════════
--  ③ 확인 — 소모임 말머리가 어떻게 되었는지
-- ═══════════════════════════════════════════════════════════
select coalesce(substring(title from '^\[([^\]]+)\]'), '(말머리 없음)') as "말머리",
       count(*)                                                        as "건수"
  from public.posts
 where org = 'OB' and category = 'club'
 group by 1
 order by 2 desc;

-- 되살아난 전공별 글 목록
select left(title, 70) as "제목", created_at::date as "쓴 날"
  from public.posts
 where org = 'OB' and category = 'club' and title ~ '^\[전공별\]'
 order by created_at desc;

