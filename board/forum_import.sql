-- ── 1) 기존 게시판에 흩어져 있던 단과대·전공별 모임 글을 단과대포럼으로 이동 ──
update public.posts
set category = 'forum',
    title = '[기타] ' || regexp_replace(title, '^\s*\[[^\]]*\]\s*', ''),
    visibility = 'members'
where category in ('free', 'club', 'faculty')
  and (
    title ~ '(단과대|전공별 ?(모임|포럼)|구조계|농학생명|응용화학|화학공학|도시공학|건축학 ?(동문|포럼)|학과별 ?모임)'
    or title ~ '(계열|학부|대학원) ?(동문 ?)?(모임|포럼)'
  );

-- 건축 관련은 [건축학] 말머리로
update public.posts
set title = '[건축학] ' || regexp_replace(title, '^\s*\[[^\]]*\]\s*', '')
where category = 'forum' and title ~ '(건축|구조계|도시)';

-- 농학·생명 관련은 [농학생명] 말머리로
update public.posts
set title = '[농학생명] ' || regexp_replace(title, '^\s*\[[^\]]*\]\s*', '')
where category = 'forum' and title ~ '(농학|생명과학|수의|식품)';

-- 화학·공학 관련은 [공학] 말머리로
update public.posts
set title = '[공학] ' || regexp_replace(title, '^\s*\[[^\]]*\]\s*', '')
where category = 'forum' and title ~ '(화학공학|응용화학|기계|전기|재료)';


